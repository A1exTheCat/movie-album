create table if not exists public.album_entries (
  id bigint generated by default as identity primary key,
  tmdb_id bigint not null unique,
  watched boolean not null default false,
  added_at timestamptz not null default now(),
  watched_at timestamptz
);

alter table public.album_entries enable row level security;

grant select, insert, update, delete on public.album_entries to anon, authenticated;
grant usage, select on sequence public.album_entries_id_seq to anon, authenticated;

create policy "Anyone can read album entries"
  on public.album_entries for select to anon, authenticated using (true);

create policy "Anyone can add album entries"
  on public.album_entries for insert to anon, authenticated with check (true);

create policy "Anyone can update album entries"
  on public.album_entries for update to anon, authenticated using (true) with check (true);

create policy "Anyone can delete album entries"
  on public.album_entries for delete to anon, authenticated using (true);
